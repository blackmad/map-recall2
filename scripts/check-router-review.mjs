/** Exercise review persistence and keyboard controls in an isolated copy of the queue. */
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium, expect } from '@playwright/test';
const root = await fs.mkdtemp(path.resolve('.cache/facade-rebuild/router-review-check-'));
await fs.cp('.cache/facade-rebuild/router-review/images', path.join(root, 'images'), { recursive: true });
await fs.copyFile('.cache/facade-rebuild/router-review/manifest.json', path.join(root, 'manifest.json'));
const server = spawn(process.execPath, ['scripts/facade-rebuild/serve-router-review.mjs'], { env: { ...process.env, ROUTER_REVIEW_ROOT: root, ROUTER_REVIEW_PORT: '5294' }, stdio: ['ignore', 'pipe', 'pipe'] });
await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(Error('Server startup timeout')), 10000); server.stdout.once('data', () => { clearTimeout(timer); resolve(); }); server.once('error', reject); server.once('exit', code => { if (code) reject(Error('Server exited')); }); });
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5294/');
  await page.locator('#choices button').first().waitFor();
  await page.locator('#reviewer').fill('automated-test'); await page.locator('h1').click();
  await page.keyboard.press('1'); await page.waitForFunction(() => document.querySelector('#progress').textContent.startsWith('1 /'));
  await page.keyboard.press('z'); await page.waitForFunction(() => document.querySelector('#progress').textContent.startsWith('0 /'));
  await page.keyboard.press('2'); await page.waitForFunction(() => document.querySelector('#progress').textContent.startsWith('1 /'));
  await page.reload(); await page.locator('#choices button').first().waitFor();
  assert.match(await page.locator('#progress').textContent(), /^1 \/ 19/);
  await page.keyboard.press('Space'); assert.equal(await page.locator('#zoom').evaluate(e => e.open), true);
  await page.keyboard.press('Escape'); assert.equal(await page.locator('#zoom').evaluate(e => e.open), false);
  const before = await page.locator('#progress').textContent();
  await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', { key: '1', repeat: true })));
  assert.equal(await page.locator('#progress').textContent(), before);
  await page.locator('#task').selectOption('awning'); await page.locator('h1').click(); await page.keyboard.press('3');
  await page.waitForFunction(() => document.querySelector('#progress').textContent.startsWith('1 /'));
  const session = await (await fetch('http://127.0.0.1:5294/api/session')).json();
  assert.equal(session.labels.labels.length, 2);
  const stale = await fetch('http://127.0.0.1:5294/api/label', { method: 'POST', headers: { 'content-type': 'application/json', 'x-review-token': session.csrf }, body: JSON.stringify({ ...session.labels.labels[0], sourceSha256: 'stale' }) });
  assert.equal(stale.status, 400);
  const machineImport = await fetch('http://127.0.0.1:5294/api/import', { method: 'POST', headers: { 'content-type': 'application/json', 'x-review-token': session.csrf }, body: JSON.stringify({ ...session.labels, labels: [{ ...session.labels.labels[0], origin: 'machine-proposal' }] }) });
  assert.equal(machineImport.status, 400);
  assert.equal((await (await fetch('http://127.0.0.1:5294/api/export')).json()).labels.length, 2);
  await page.locator('summary').click(); await page.locator('#train').click();
  await expect.poll(async () => (await (await fetch('http://127.0.0.1:5294/api/training')).json()).status, { timeout: 30000 }).toBe('complete');
  const training = await (await fetch('http://127.0.0.1:5294/api/training')).json();
  assert.ok(Object.values(training.report.tasks).every(t => t.status === 'needs-labels'));
  await page.locator('summary').click();
  await page.waitForFunction(() => [...document.images].every(i => i.complete && i.naturalWidth > 0));
  await page.screenshot({ path: path.join(root, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(root, 'mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'passed', checks: ['keyboard answer', 'undo', 'reload persistence', 'zoom', 'key repeat prevention', 'task switch', 'stale source rejection', 'machine label import rejection', 'training button and insufficient-label response', 'image loading', 'mobile overflow'], captures: root }));
} finally { await browser?.close(); server.kill('SIGTERM'); }
