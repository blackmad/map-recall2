// Writes src/canalRecall/houseboatKindOverrides.ts from the orthophoto labels: every
// labelled boat on the ride corridors (the ring canals, Brouwersgracht, the Amstel),
// whose kind the footprint alone cannot tell. --check fails when the file is stale.
//   npx tsx scripts/houseboat-kinds/overrides.ts [--check]
import fs from 'node:fs';

export const CORRIDOR_WATER = /Prinsengracht|Herengracht|Keizersgracht|^Singel$|Brouwersgracht|Amstel/;
const OUT = 'src/canalRecall/houseboatKindOverrides.ts';
const { boats } = JSON.parse(fs.readFileSync('scripts/houseboat-kinds/labels.json', 'utf8')) as { boats: Record<string, { label: string; water: string; note?: string }> };
const rows = Object.entries(boats).filter(([, b]) => b.label !== 'none' && CORRIDOR_WATER.test(b.water)).sort(([a], [b]) => a.localeCompare(b));
const text = `// Generated by scripts/houseboat-kinds/overrides.ts from scripts/houseboat-kinds/labels.json
// (PDOK 8 cm orthophoto, labelled 2026-10-16). Do not edit by hand: relabel and regenerate.
import type { HouseboatKind } from './houseboats.js';

/** Boats on the ride corridors whose kind was read off the orthophoto. */
export const LABELLED_HOUSEBOAT_KINDS: Readonly<Record<string, HouseboatKind>> = {
${rows.map(([id, b]) => `  ${id}: '${b.label}', // ${b.water}${b.note ? `; ${b.note}` : ''}`).join('\n')}
};
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(OUT, 'utf8') !== text) { console.error(`${OUT} is stale: npx tsx scripts/houseboat-kinds/overrides.ts`); process.exit(1); }
  console.log(`${OUT}: ${rows.length} boats, in sync`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`${OUT}: ${rows.length} boats`);
}
