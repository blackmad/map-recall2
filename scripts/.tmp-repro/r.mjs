import { chromium } from 'playwright';
const b = await chromium.launch({args:['--use-gl=swiftshader','--enable-unsafe-swiftshader']});
const p = await b.newPage();
p.on('console', m => { if (m.type()==='error'||m.type()==='warning') console.log('[console]', m.type(), m.text().slice(0,400)); });
p.on('pageerror', e => console.log('[pageerror]', e.message, '\n', (e.stack||'').slice(0,2500)));
p.on('requestfailed', r => console.log('[reqfail]', r.url(), r.failure()?.errorText));
p.on('response', r => { if (r.status()>=400) console.log('[http]', r.status(), r.url()); });
await p.goto(process.argv[2], {waitUntil:'load', timeout:90000});
await p.waitForTimeout(25000);
await b.close();
