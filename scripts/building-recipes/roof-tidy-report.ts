/**
 * Roof clean-up census for installed `kind: large` houses (issue #87): per house the roof pieces, slivers under 4 m²,
 * distinct flat levels and spikes, as drawn today and with `roof.tidy` (roofTidy.ts) applied in memory.
 *
 *   node --import tsx scripts/building-recipes/roof-tidy-report.ts [--out=docs/reports/roof-cleanup-20261109.md] [--json]
 *
 * Installed = a kind:large house with a row in large-mesh-golden.json. Writes nothing but the report.
 */
import fs from 'node:fs';
import {roofMetrics, tidyRoof, type RoofMetrics} from '../../src/canalRecall/buildingRecipe/roofTidy.ts';
import type {BuildingFacts} from '../../src/canalRecall/buildingRecipe/facts.ts';

const HOUSES = 'scripts/building-recipes/houses';
const arg = (n: string) => process.argv.find(a => a.startsWith(`--${n}=`))?.slice(n.length + 3);
const golden = JSON.parse(fs.readFileSync('scripts/building-recipes/large-mesh-golden.json', 'utf8')) as Record<string, string>;
const FLAGGED = ['warmoesstraat-garage-165687', 'van-eeghenstraat-97-237151'];
const rows: {id: string; before: RoofMetrics; after: RoofMetrics; actions: string}[] = [];
for (const id of Object.keys(golden)) {
  const dir = `${HOUSES}/${id}`;
  if (!fs.existsSync(`${dir}/intent.json`) || !fs.existsSync(`${dir}/facts.json`)) continue;
  const intent = JSON.parse(fs.readFileSync(`${dir}/intent.json`, 'utf8'));
  if (intent.kind !== 'large') continue;
  const facts = JSON.parse(fs.readFileSync(`${dir}/facts.json`, 'utf8')) as BuildingFacts;
  const {report} = tidyRoof(facts, {frontSurfaces: (intent.walls ?? []).flatMap((w: {wallSurfaces: number[]}) => w.wallSurfaces)});
  rows.push({id, before: report.before, after: report.after, actions: `${report.mergedLevels} merged, ${report.foldedSlivers} folded, ${report.clampedSpikes} spikes, ${report.protectedPlanes} protected`});
}
const score = (m: RoofMetrics) => m.slivers + m.flatLevels + m.spikes * 5;
rows.sort((a, b) => score(b.before) - score(a.before));
if (process.argv.includes('--json')) console.log(JSON.stringify(rows, null, 1));
const line = (r: typeof rows[number]) => `| ${r.id} | ${r.before.pieces} | ${r.before.slivers} (${r.before.stepped}) | ${r.before.flatLevels} | ${r.before.spikes} | ${r.after.stepped} | ${r.after.flatLevels} | ${r.after.spikes} | ${r.actions} |`;
const head = '| house | pieces | slivers <4 m² (stepped) | flat levels | spikes | stepped after | levels after | spikes after | tidy actions |\n|---|---|---|---|---|---|---|---|---|';
const sum = (f: (r: typeof rows[number]) => number) => rows.reduce((n, r) => n + f(r), 0);
const md = `# Roof clean-up census, ${new Date().toISOString().slice(0, 10)} (issue #87)

Generated by \`scripts/building-recipes/roof-tidy-report.ts\`. ${rows.length} installed \`kind: large\` houses (rows in large-mesh-golden.json).
Before = 3DBAG LoD2.2 roof planes as the large tier draws them; after = \`roof.tidy\` applied in memory (roofTidy.ts), nothing installed.
Stepped = a sliver more than 0.15 m off a plane it touches. Spike = a plane under 4 m² standing more than 0.8 m over the highest plane it touches (or touching none). Levels = single-linkage clusters (0.1 m) of flat-plane heights.

- Houses with 10 or more slivers: ${rows.filter(r => r.before.slivers >= 10).length} before, ${rows.filter(r => r.after.slivers >= 10).length} after.
- Houses with 6 or more flat levels: ${rows.filter(r => r.before.flatLevels >= 6).length} before, ${rows.filter(r => r.after.flatLevels >= 6).length} after.
- Total slivers ${sum(r => r.before.slivers)} (stepped against a neighbour: ${sum(r => r.before.stepped)} -> ${sum(r => r.after.stepped)}); total flat levels ${sum(r => r.before.flatLevels)} -> ${sum(r => r.after.flatLevels)}; spikes ${sum(r => r.before.spikes)} -> ${sum(r => r.after.spikes)}.

## Worst 20 (slivers + levels + spikes x5, before)

${head}
${rows.slice(0, 20).map(line).join('\n')}

## Flagged by the user

${head}
${rows.filter(r => FLAGGED.includes(r.id)).map(line).join('\n')}
`;
const out = arg('out'); if (out) fs.writeFileSync(out, md); else console.log(md);
