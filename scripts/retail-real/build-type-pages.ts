/**
 * Lettering pages (lane retail-real-20261115, src/canalRecall/retailTypeFaces.ts): each face's glyphs, white on black,
 * shelf-packed by advance onto a 512 px page, and their rects in src/canalRecall/retailTypeMetrics.gen.ts. Fonts are SIL
 * OFL from github.com/google/fonts (data/retail-ground/fonts, licences beside them).
 *   node --import tsx scripts/retail-real/build-type-pages.ts [--publish]
 * Stages data/retail-ground/type-<face>.png; --publish copies them to public/canal-drive/materials/retail-logos/.
 */
import fs from 'node:fs';
import { createCanvas, GlobalFonts } from '@napi-rs/canvas';
import { TYPE_CHARS, TYPE_FACES, TYPE_PAGE, type TypeFace } from '../../src/canalRecall/retailTypeFaces.ts';

const FONTS: Record<TypeFace, { file: string; family: string; source: string }> = {
  serif: { file: 'data/retail-ground/fonts/abrilfatface-AbrilFatface-Regular.ttf', family: 'RR Abril', source: 'https://github.com/google/fonts/tree/main/ofl/abrilfatface' },
  condensed: { file: 'data/retail-ground/fonts/bebasneue-BebasNeue-Regular.ttf', family: 'RR Bebas', source: 'https://github.com/google/fonts/tree/main/ofl/bebasneue' },
  script: { file: 'data/retail-ground/fonts/lobster-Lobster-Regular.ttf', family: 'RR Lobster', source: 'https://github.com/google/fonts/tree/main/ofl/lobster' },
};
const { size: P, rowPx, fontPx, basePx, gapPx } = TYPE_PAGE;
const metrics: Record<string, { cap: number; space: number; glyphs: Record<string, [number, number, number]> }> = {};
for (const face of TYPE_FACES) {
  const f = FONTS[face];
  GlobalFonts.registerFromPath(f.file, f.family);
  const c = createCanvas(P, P), ctx = c.getContext('2d');
  ctx.fillStyle = '#000'; ctx.fillRect(0, 0, P, P);
  ctx.font = `${fontPx}px "${f.family}"`; ctx.fillStyle = '#fff'; ctx.textBaseline = 'alphabetic';
  const glyphs: Record<string, [number, number, number]> = {};
  let x = gapPx, row = 0;
  // Bebas has no lower case (its lower-case slots repeat the capitals): uppercase only.
  const chars = face === 'condensed' || face === 'serif' ? [...TYPE_CHARS].filter(ch => !/[a-z]/.test(ch)) : [...TYPE_CHARS];
  for (const ch of chars) {
    const adv = Math.ceil(ctx.measureText(ch).width);
    if (x + adv + gapPx > P) { x = gapPx; row++; }
    if ((row + 1) * rowPx > P) throw new Error(`${face}: page full at ${ch}`);
    ctx.save(); ctx.beginPath(); ctx.rect(x, row * rowPx, adv, rowPx); ctx.clip();
    ctx.fillText(ch, x, row * rowPx + basePx); ctx.restore();
    glyphs[ch] = [x, row, adv];
    x += adv + gapPx;
  }
  const H = ctx.measureText('H'), cap = (H.actualBoundingBoxAscent ?? fontPx * 0.7) / rowPx;
  metrics[face] = { cap: +cap.toFixed(3), space: +(ctx.measureText(' ').width / rowPx).toFixed(3), glyphs };
  fs.writeFileSync(`data/retail-ground/type-${face}.png`, c.toBuffer('image/png'));
  if (process.argv.includes('--publish')) fs.copyFileSync(`data/retail-ground/type-${face}.png`, `public/canal-drive/materials/retail-logos/type-${face}.png`);
  console.log(`${face}: ${Object.keys(glyphs).length} glyphs in ${row + 1} rows, cap ${cap.toFixed(3)} of the quad (${f.source})`);
}
fs.writeFileSync('src/canalRecall/retailTypeMetrics.gen.ts', `// Generated by scripts/retail-real/build-type-pages.ts: each face's glyph [x px, row, advance px] on its page.\n` +
  `export const TYPE_METRICS: Record<string, { cap: number; space: number; glyphs: Record<string, [number, number, number]> }> = ${JSON.stringify(metrics)};\n`);
