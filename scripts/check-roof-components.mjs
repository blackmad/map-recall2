import assert from 'node:assert/strict';
import {roofFrontageComponents} from './da-costa-block/roof-components.mjs';
const roof=(ring,holes=[])=>({type:'roof',rings:[ring,...holes]});
const rect=(x0,x1,z0,z1,h0,h1=h0)=>[[x0,h0,z0],[x1,h0,z0],[x1,h1,z1],[x0,h1,z1]];
const wall={localStart:[0,0],localEnd:[10,0]};
const run=surfaces=>roofFrontageComponents({id:'synthetic',surfaces},wall);
const deck=roof(rect(0,10,2,12,10));
let r=run([deck,roof(rect(0,10,0,2,8,10))]);
assert.deepEqual(r.facts.mainDeckAdjoiningFrontPitchFaceIndices,[1]);
assert.equal(r.pitchedFaces[0].frontage.edgeContactOverlapM,10);
assert.equal(r.pitchedFaces[0].deckRelation.verticalRelation,'height-compatible');
assert.deepEqual(r.facts.substantiveMainDeckHeightFrontagePitchFaceIndices,[1]);
r=run([deck,roof(rect(0,10,0,2,2,3))]);
assert.deepEqual(r.facts.lowerLevelPitchFaceIndices,[1]);
assert.deepEqual(r.facts.mainDeckAdjoiningFrontPitchFaceIndices,[]);
r=run([deck,roof(rect(0,10,0,2,18,20))]);
assert.equal(r.pitchedFaces[0].deckRelation.verticalRelation,'above-reference-deck');
assert.deepEqual(r.pitchedFaces[0].deckRelation.adjoiningReferenceFaceIndices,[]);
r=run([deck,roof(rect(0,.3,0,.3,8,8.3))]);
assert.equal(r.pitchedFaces.length,1);assert.ok(r.pitchedFaces[0].areaM2<.5);
assert.deepEqual(r.facts.substantiveFrontagePitchFaceIndices,[],'Retain tiny faces without routing main-roof questions from them');
r=run([roof(rect(0,10,3,12,10)),roof(rect(0,10,1,3,8,10))]);
assert.equal(r.pitchedFaces[0].frontage.association,'projected-nearby');
assert.deepEqual(r.facts.mainDeckAdjoiningFrontPitchFaceIndices,[]);
r=run([deck,roof(rect(10,12,0,2,8,10))]);
assert.deepEqual(r.pitchedFaces[0].deckRelation.adjoiningReferenceFaceIndices,[],'Corner-only contact is not physical edge attachment');
const holed=roof(rect(0,10,0,10,10),[rect(2,4,2,4,10)]);
r=run([holed,roof(rect(2,4,2,4,8,10))]);
assert.equal(r.mainDeckCandidate.projectedAreaM2,96,'Subtract interior-ring area');
assert.deepEqual(r.pitchedFaces[0].deckRelation.adjoiningReferenceFaceIndices,[0],'Physical roof contact at hole boundary must be retained');
r=run([deck]);assert.equal(r.facts.noPitchObservedInMesh,true);assert.equal(r.absenceIsEvidenceOfAbsence,false);assert.equal(r.authoritativeRoofClass,null);
r=run([roof(rect(0,5,2,12,10)),roof(rect(5,10,2,12,10)),roof(rect(0,10,0,2,8,10))]);
assert.deepEqual(r.mainDeckCandidate.sourceFaceIndices,[0,1]);
assert.deepEqual(r.pitchedFaces[0].deckRelation.adjoiningReferenceFaceIndices,[0,1]);
assert.throws(()=>roofFrontageComponents({surfaces:[]},{localStart:[0,0],localEnd:[0,0]}));
console.log('Roof component tests passed: tiny faces, edge/height contact, lower annex, proximity, corner-only exclusion, holes, connected decks and non-evidence of absence.');
