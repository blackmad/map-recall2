/** Outward normal of a wall drawn west to east with the street to the south. */
const normal = (w: WallQuad) => { const vx = w.b.x - w.a.x, vy = w.b.y - w.a.y, l = Math.hypot(vx, vy); return { nx: vy / l, ny: -vx / l }; };

function fpsAt(id: string, distM: number) {
  const f = FRONTS.find(x => x.id === id)!, n = normal(f.wall);
  const mid: Rd = { x: (f.wall.a.x + f.wall.b.x) / 2 + n.nx * distM, y: (f.wall.a.y + f.wall.b.y) / 2 + n.ny * distM };
  const pose = fixedLensPose({ lngLat: rdToLngLat(mid) as [number, number], eyeHeightM: FPS_EYE_HEIGHT_M }, f.wall);
  const o = wallOutline(frameFor(pose), pose, f.wall).filter(Boolean) as Array<{ x: number; y: number }>;
  const box = { x0: Math.max(0, Math.min(...o.map(p => p.x))), x1: Math.min(pose.width, Math.max(...o.map(p => p.x))), y0: Math.max(0, Math.min(...o.map(p => p.y))), y1: Math.min(pose.height, Math.max(...o.map(p => p.y))) };
  return { pandId: id, distM, lngLat: pose.lngLat, headingDeg: pose.headingDeg, vfovDeg: pose.vfovDeg, lookDownDeg: pose.lookDownDeg, clipped: pose.clipped, fps: fpsFor(pose), wallBoxCss: box };
}

