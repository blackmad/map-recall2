// Round 7: merge the brand readers' JSON (artifacts/retail-real/r7/brand-reads-*.json, one object per chain, read on
// 2–3 newest panorama crops per chain, front-photos.ts) into src/canalRecall/retailBrandStyles.gen.ts, with each crop's
// panorama and date from the cut receipts and a source URL per brand (its Wikidata item, else its Commons logo file).
//   node --import tsx scripts/retail-ground/brand-styles.ts [--dir=artifacts/retail-real/r7] [--fetched=2026-11-16]
import fs from 'node:fs';
import path from 'node:path';
import { RETAIL_CHAINS_GEN } from '../../src/canalRecall/retailChains.gen.js';

const arg = (k: string, d: string) => process.argv.find(a => a.startsWith(`--${k}=`))?.slice(k.length + 3) ?? d;
const dir = arg('dir', 'artifacts/retail-real/r7'), fetched = arg('fetched', '2026-11-16');
const receipts = new Map<string, { pano: string; date: string }>(
  Object.entries(JSON.parse(fs.readFileSync(path.join(dir, 'photos/receipts.json'), 'utf8')) as Record<string, { file: string; pano: string; date: string }>)
    .filter(([, r]) => r.file).map(([, r]) => [path.basename(r.file), { pano: r.pano, date: r.date }]));
const logos = new Map((JSON.parse(fs.readFileSync('data/retail-ground/retail-logos.json', 'utf8')).logos as Array<{ key: string; source: string }>).map(l => [l.key, l.source]));
// Template chains with no Wikidata in RETAIL_CHAINS_GEN and no Commons logo: their OSM brand:wikidata.
const WIKIDATA_EXTRA: Record<string, string> = { febo: 'Q582245' };
// No Wikidata item and no Commons logo: the brand's own site (web search 2026-11-16; Het Zwarte Fietsenplan's is in
// data/retail-ground/chain-logo-sources.json).
const SITE_EXTRA: Record<string, string> = { stach: 'https://www.stach-food.nl/', 'het-zwarte-fietsenplan': 'https://www.hetzwartefietsenplan.nl/' };
const sourceOf = (k: string): string | null => {
  const q = (RETAIL_CHAINS_GEN[k] as { wikidata?: string } | undefined)?.wikidata ?? WIKIDATA_EXTRA[k];
  if (q) return `https://www.wikidata.org/wiki/${q}`;
  const f = logos.get(k);
  return f ? `https://commons.wikimedia.org/wiki/${encodeURI(f.replace(/ /g, '_'))}` : SITE_EXTRA[k] ?? null;
};
const out: Record<string, unknown> = {};
const files = fs.readdirSync(dir).filter(f => /^brand-reads-.*\.json$/.test(f)).sort();
for (const f of files) for (const r of JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')) as Array<Record<string, unknown> & { chain: string; crops: string[] }>) {
  const src = sourceOf(r.chain);
  if (!src) { console.warn(`${r.chain}: no source URL, left out`); continue; }
  const panoramas = r.crops.map(c => receipts.get(c) ?? (/(\d{4}-\d{2}-\d{2})/.exec(c) ? { pano: c.replace(/\.\w+$/, ''), date: /(\d{4}-\d{2}-\d{2})/.exec(c)![1] } : null)).filter(Boolean);
  const { chain: _c, crops: _x, ...rest } = r;
  out[r.chain] = { ...rest, panoramas, source: { url: src, fetched } };
}
const keys = Object.keys(out).sort();
fs.writeFileSync('src/canalRecall/retailBrandStyles.gen.ts', `// Generated by scripts/retail-ground/brand-styles.ts from ${dir}/brand-reads-*.json; do not edit.\nexport const BRAND_STYLES_GEN: Record<string, unknown> = {\n${keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join('\n')}\n};\n`);
console.log(`${keys.length} brands -> src/canalRecall/retailBrandStyles.gen.ts (${files.join(', ')})`);
