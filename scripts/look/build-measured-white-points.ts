// The white points measured walls were recorded under, for the sunny look's exposure normalisation.
//   npx tsx scripts/look/build-measured-white-points.ts [--write]
// Reads every scripts/building-recipes/houses/*/measured.json (measureFacade.ts `normalisation`: `ref` is the raw
// light-trim white of the crop, `gain` and `wb` what the measurement applied to it) and writes
// src/canalRecall/look/measuredWhitePoints.ts:
//   SUNLIT_WHITE_LUMA   median luma of the raw light-trim white over the crops captured May-September (summer sun);
//   WALL_WHITE_POINTS   measured wall hex -> the white that hex is relative to (ref x gain x wb, i.e. the crop's
//                       light trim after normalisation), for walls whose crop had a light-trim reference;
//   FALLBACK_WALL_GAIN  the linear gain for a measured wall with no recorded white: the median over the crops with
//                       one of lin(SUNLIT_WHITE_LUMA) / lin(raw white luma) (what normalising to a sunlit white would
//                       have done to that raw crop).
import fs from 'node:fs';
import path from 'node:path';

const HOUSES = 'scripts/building-recipes/houses';
const OUT = 'src/canalRecall/look/measuredWhitePoints.ts';
type RGB = [number, number, number];
const luma = (c: readonly number[]) => 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
const lin = (v: number) => { const s = v / 255; return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4; };
const med = (a: number[]) => { const s = a.slice().sort((p, q) => p - q); return s.length % 2 ? s[s.length >> 1] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2; };

const rows: { house: string; group: number; month: number; wall: string; ref: RGB | null; white: RGB | null }[] = [];
for (const house of fs.readdirSync(HOUSES).sort()) {
  const f = path.join(HOUSES, house, 'measured.json');
  if (!fs.existsSync(f)) continue;
  for (const g of JSON.parse(fs.readFileSync(f, 'utf8')).groups ?? []) {
    const m = g.measured; if (!m?.wall) continue;
    const n = m.normalisation ?? {}, ref: RGB | null = n.ref ?? null;
    const white = ref ? ref.map((v: number, i: number) => Math.min(255, Math.round(v * (n.gain ?? 1) * (n.wb?.[i] ?? 1)))) as RGB : null;
    rows.push({ house, group: g.group, month: Number(String(g.crop?.capturedAt ?? '').slice(5, 7)), wall: String(m.wall).toLowerCase(), ref, white });
  }
}
const withRef = rows.filter(r => r.ref);
const summer = withRef.filter(r => r.month >= 5 && r.month <= 9);
const SUNLIT = Math.round(med(summer.map(r => luma(r.ref!))));
const FALLBACK = +med(withRef.map(r => lin(SUNLIT) / lin(luma(r.ref!)))).toFixed(3);
const points: Record<string, RGB> = {};
for (const r of withRef) if (!points[r.wall]) points[r.wall] = r.white!;
const src = `// Generated by scripts/look/build-measured-white-points.ts from scripts/building-recipes/houses/*/measured.json; do not edit.
// ${rows.length} measured wall groups, ${withRef.length} with a light-trim white (${summer.length} captured May-September).

/** Median luma of the raw light-trim white over the summer captures (May-September, n = ${summer.length}). */
export const SUNLIT_WHITE_LUMA = ${SUNLIT};
/** Linear gain for a measured wall with no recorded white: median over the ${withRef.length} crops with one of lin(SUNLIT) / lin(raw white). */
export const FALLBACK_WALL_GAIN = ${FALLBACK};
/** Measured wall hex -> the white it is relative to (the crop's light trim after normalisation, sRGB). */
export const WALL_WHITE_POINTS: Readonly<Record<string, readonly [number, number, number]>> = {
${Object.entries(points).map(([k, v]) => `  '${k}': [${v.join(', ')}],`).join('\n')}
};
`;
console.log({ groups: rows.length, withRef: withRef.length, summer: summer.length, SUNLIT, FALLBACK, hexes: Object.keys(points).length });
if (process.argv.includes('--write')) { fs.writeFileSync(OUT, src); console.log('wrote', OUT); }
