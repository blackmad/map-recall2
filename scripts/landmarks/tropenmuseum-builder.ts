/**
 * Tropenmuseum / Koninklijk Instituut voor de Tropen, Linnaeusstraat 2 (BAG 0363100012237251; J.J. and M.A. van Nieukerken, 1913, opened 1926).
 *
 * Massing: the 3DBAG LoD2.2 walls and roofs verbatim (tropenmuseum-facts.json, from facts.ts --large), through the large-tier fit and
 * block-kit compose with the wall groups of tropenmuseum-intent.json (generated by tropenmuseum-groups.ts). Everything the facade systems
 * cannot express is drawn here from the panoramas and the Rijksmonument 526987 register text; see tropenmuseum-inventory.json.
 *
 * Local frame = the large tier's: x east, z south, y up from the 3DBAG ground, origin the mean of the 3DBAG LoD0 outline vertices.
 */
const FACTS = factsJson as unknown as BuildingFacts;
/**
 * The two museum pavilions' tent roofs (local x, z, apex height of the steep planes). 3DBAG approximates the copper helmet above each apex
 * as a thin spike of 3-5 planes (42.5-45.3 m); those triangles are dropped and a lantern, onion helmet, spire, ball and vane are modelled
 * from the panoramas (w10-61, w16-61: onion helmet with a finial rod) within the same 45.3 m.
 */
/** Debug switches for isolating one part of the model (formerly the TROP_* environment variables); the shipped build uses none. */
export interface TropenmuseumOptions extends PavilionOptions {
  /** no copper helmets on the two museum pavilions */
  noHelmet?: boolean;
  /** leave the measured pavilion faces out (the kit draws plain windows there) */
  noFaces?: boolean;
  /** skip every bespoke panel hook (portal, pavilions, gable crowns) */
  plain?: boolean;
  /** keep the window cells that look into the light courts (the shipped build leaves them as plain brick, see tropenmuseum-hidden.ts) */
  keepHiddenCells?: boolean;
  /** leave out the portal, the gable crowns or the pavilion rule ornaments (clock dial, rule relief frieze) */
  without?: ('portal' | 'crowns' | 'ornaments' | 'block' | 'gablewing' | 'risalit')[];
}
/** Dropping 3DBAG's spike opens boundary loops in the shell (audit holes), so the modelled helmet is seated over it instead. */
const REMOVE_SPIKE = false;
const HELMETS: {x: number; z: number; y0: number; top: number}[] = [{x: 80.6, z: -42.5, y0: 40.9, top: 45.3}, {x: 98.0, z: -11.2, y0: 42.2, top: 45.2}];
const PALETTE: Record<string, 'brick' | 'stone' | 'glass' | 'frame' | 'dark' | 'slate' | 'white'> = {
  brick: 'brick', stucco: 'white', stone: 'stone', glass: 'glass', frame: 'frame', door: 'dark', accent: 'dark', slate: 'slate', roofTile: 'slate', bitumen: 'slate',
};
const SET = largeSurfaceSet(FACTS).set;
/** surfaces of a panel (3DBAG LoD2.2 boundary indices) */
const surfacesOf = (p: Panel) => p.walls.map(k => SET.walls[k]?.surface ?? -1);
const has = (p: Panel, ...ids: number[]) => surfacesOf(p).some(x => ids.includes(x));


/** Museum corner pavilions (panels 322, 330, 152): relief friezes, anchors, clock dials. */
const PAVILIONS: {surfaces: number[]; dial: boolean}[] = [{surfaces: [379], dial: false}, {surfaces: [388], dial: false}, {surfaces: [168], dial: false}];
/** Single-peak gable walls the street sees (gables.ts survey): crowned with piers, balls and an apex finial; `statue` for the broad ones. */
const GABLES: {surfaces: number[]; statue: boolean}[] = [
  {surfaces: [210, 283], statue: true}, {surfaces: [151, 154], statue: true}, {surfaces: [148, 233], statue: true}, {surfaces: [119, 776], statue: false},
  {surfaces: [129, 299, 301], statue: false}, {surfaces: [236, 502, 503], statue: false}, {surfaces: [17, 62], statue: false}, {surfaces: [12, 215, 779, 989], statue: false},
  {surfaces: [68, 257, 432], statue: false}, {surfaces: [966, 1058, 1196, 1198], statue: false},
];

export interface TropenmuseumStats extends KitStats {triangles: number}

/** A panel whose face is drawn by hand (the kit's cells there are skipped or overdrawn). */
function bespokePanel(p: Panel): boolean {
  const sf = surfacesOf(p);
  if (has(p, ...PORTAL_SURFACES)) return true;
  if (gableWingOf(sf)?.panel === p.index || risalitOf(sf)?.panel === p.index || pavilionWallOf(sf)?.panel === p.index) return true;
  return PAVILIONS.some(q => has(p, ...q.surfaces));
}

export function tropenmuseumHooks(stats: TropenmuseumStats, opt: TropenmuseumOptions = {}, hidden?: Set<string>, collect?: CellsByPanel, courtPanels?: Set<number>): LargeCompileHooks {
  return {
    budget: 40000,
    // court faces (every window cell looks at another wall within 40 m): no string courses or cornice either
    // and none across the measured faces (portal, pavilions, gable wing, risalit), which draw their own courses and cornices
    skipBands: (p: Panel) => !!courtPanels?.has(p.index) || bespokePanel(p),
    barOffsetM: BAR,
    afterCompose: (_m, recipe) => { recipe.spec.palette[IRON] = '#3a3a3a'; }, // wrought-iron slot, see IRON in the kit
    skipCell: (p, floor, bay) => {
      if (has(p, ...PORTAL_SURFACES)) return true;
      if (hidden?.has(`${p.index}:${floor}:${bay}`)) return true;
      if (opt.noFaces) return false;
      const gw = opt.without?.includes('gablewing') ? undefined : gableWingOf(surfacesOf(p));
      if (gw && gw.panel === p.index) return floor >= gw.skipFrom;
      const rs = opt.without?.includes('risalit') ? undefined : risalitOf(surfacesOf(p));
      if (rs && rs.panel === p.index) return true;
      const w = pavilionWallOf(surfacesOf(p));
      return !!w && w.panel === p.index && floor < skipFloors(w);
    },
    panelHook: (c, info) => {
      collect?.set(c.p.index, info.cells);
      if (opt.plain) return;
      if (has(c.p, ...PORTAL_SURFACES)) { if (opt.without?.includes('portal')) return; portalFront(c, stats); portalGable(c, stats); return; }
      const eaves = panelEaves(c.p);
      const gw = opt.without?.includes('gablewing') ? undefined : gableWingOf(surfacesOf(c.p));
      if (gw && gw.panel === c.p.index) gableWingFace(c, stats, gw);
      const rs = opt.without?.includes('risalit') ? undefined : risalitOf(surfacesOf(c.p));
      if (rs && rs.panel === c.p.index) risalitFace(c, stats, rs);
      const pav = PAVILIONS.find(q => has(c.p, ...q.surfaces));
      const face = opt.noFaces ? undefined : pavilionWallOf(surfacesOf(c.p));
      if (face && face.panel === c.p.index) { pavilionFace(c, stats, face, opt); if (face.block && !opt.without?.includes('block')) connectingBlock(c, stats, face as typeof face & {block: BlockSpec}); }
      if (pav && !opt.without?.includes('ornaments')) pavilionOrnaments(c, stats, info.cells, eaves, pav.dial, !!face && face.panel === c.p.index);
      const crown = GABLES.find(g => has(c.p, ...g.surfaces));
      if (crown && !opt.without?.includes('crowns')) gableCrown(c, stats, eaves, crown.statue);
    },
  };
}

export function compileTropenmuseum(opt: TropenmuseumOptions = {}) {
  const intent = validateLargeIntent(intentJson);
  const stats: TropenmuseumStats = {triangles: 0, openings: 0, failed: [], drawn: []};
  let hidden: Set<string> | undefined, court: Set<number> | undefined;
  if (!opt.keepHiddenCells) {
    // pass 1 collects every panel's cells; the second pass leaves out the ones that face a court wall
    const cells: CellsByPanel = new Map();
    const first = compileLargeBuilding(intent, FACTS, tropenmuseumHooks({triangles: 0, openings: 0, failed: [], drawn: []}, {...opt, plain: true}, undefined, cells));
    hidden = hiddenCells(first.panels, cells);
    court = new Set([...cells].filter(([pi, list]) => list.length && list.every(cl => hidden!.has(`${pi}:${cl.floor}:${cl.bay}`))).map(([pi]) => pi));
  }
  const built = compileLargeBuilding(intent, FACTS, tropenmuseumHooks(stats, opt, hidden, undefined, court));
  return {built, stats};
}

export function buildTropenmuseum(_w: number, _d: number, b: BuildingTools, opt: TropenmuseumOptions = {}) {
  const {built} = compileTropenmuseum(opt);
  const all: number[] = [], glassTri: boolean[] = [];
  built.group.traverse(o => {
    if (!(o instanceof T.Mesh)) return;
    const name = o.name.endsWith('/cross') ? 'slate' : PALETTE[o.userData.materialSlot as string]; // IRON: wrought iron reads as host trim in the opening audit
    if (!name) throw Error(`tropenmuseum: no palette colour for materialSlot ${o.userData.materialSlot}`);
    const src = o.geometry as T.BufferGeometry, g = src.index ? src.toNonIndexed() : src.clone(), a = g.getAttribute('position');
    // The 3DBAG shell has sunken ramps below the street: the landmark ground is y = 0, so drop what lies fully below it and clamp the rest.
    // The spike 3DBAG draws above each pavilion's tent roof is replaced by a modelled copper helmet (HELMETS).
    const keep: number[] = [], copper: number[] = [];
    for (let i = 0; i < a.count; i += 3) {
      if (Math.max(a.getY(i), a.getY(i + 1), a.getY(i + 2)) <= 0.01) continue;
      const cy = (a.getY(i) + a.getY(i + 1) + a.getY(i + 2)) / 3, cx = (a.getX(i) + a.getX(i + 1) + a.getX(i + 2)) / 3, cz = (a.getZ(i) + a.getZ(i + 1) + a.getZ(i + 2)) / 3;
      const top = Math.max(a.getY(i), a.getY(i + 1), a.getY(i + 2));
      if (REMOVE_SPIKE && HELMETS.some(h => top > h.y0 + 0.3 && cy > h.y0 - 0.5 && Math.hypot(cx - h.x, cz - h.z) < 4.5)) continue;
      for (let k = 0; k < 3; k++) keep.push(a.getX(i + k), Math.max(0, a.getY(i + k)), a.getZ(i + k));
    }
    if (!keep.length) return;
    for (const v of keep) all.push(v);
    for (let k = 0; k < keep.length / 9; k++) glassTri.push(name === 'glass');
    const out = new T.BufferGeometry(); out.setAttribute('position', new T.Float32BufferAttribute(keep, 3)); out.computeVertexNormals();
    b.add(out, name);
  });
  const cap = capShellHoles(all, glassTri);
  if (cap.length) {
    const out = new T.BufferGeometry(); out.setAttribute('position', new T.Float32BufferAttribute(cap, 3)); out.computeVertexNormals();
    b.add(out, 'brick');
  }
  if (!opt.noHelmet) for (const h of HELMETS) helmet(b, h);
}

/**
 * Close the few large open loops that 3DBAG's own shell has (a vertical wall seam at the museum's SE pavilion: x 96-100, z -3..2, a 45 m
 * vertical edge with skewed neighbours): chain the unpaired directed edges into loops and fan-fill every loop longer than 5 m
 * (the audit lists loops above this) with at most 24 vertices. The many tiny open edges on trim are left alone.
 */
function capShellHoles(pos: number[], glassTri: boolean[] = []): number[] {
  const key = (i: number) => `${Math.round(pos[i * 3] * 50)},${Math.round(pos[i * 3 + 1] * 50)},${Math.round(pos[i * 3 + 2] * 50)}`;
  const n = pos.length / 3, edges = new Map<string, {a: number; b: number; ka: string; kb: string}>();
  for (let t = 0; t < n; t += 3) for (let k = 0; k < 3; k++) {
    const a = t + k, b = t + (k + 1) % 3, ka = key(a), kb = key(b);
    if (ka === kb) continue;
    const rev = `${kb}|${ka}`;
    if (edges.has(rev)) edges.delete(rev); else edges.set(`${ka}|${kb}`, {a, b, ka, kb});
  }
  const byStart = new Map<string, {a: number; b: number; ka: string; kb: string}[]>();
  for (const e of edges.values()) (byStart.get(e.ka) ?? byStart.set(e.ka, []).get(e.ka)!).push(e);
  const used = new Set<object>(), out: number[] = [];
  for (const first of edges.values()) {
    if (used.has(first)) continue;
    const loop = [first]; used.add(first);
    let cur = first;
    while (cur.kb !== first.ka && loop.length < 64) {
      const next = (byStart.get(cur.kb) ?? []).find(e => !used.has(e));
      if (!next) break;
      used.add(next); loop.push(next); cur = next;
    }
    if (cur.kb !== first.ka || loop.length < 3 || loop.length > 24) continue;
    // a pane laid in front of its frame sheet (pane-split glazing) is a glass quad with open edges, not a hole in the shell
    if (loop.every(e => glassTri[Math.floor(e.a / 3)])) continue;
    let perim = 0;
    for (const e of loop) perim += Math.hypot(pos[e.a * 3] - pos[e.b * 3], pos[e.a * 3 + 1] - pos[e.b * 3 + 1], pos[e.a * 3 + 2] - pos[e.b * 3 + 2]);
    if (perim < 5) continue;
    const v = loop.map(e => [pos[e.a * 3], pos[e.a * 3 + 1], pos[e.a * 3 + 2]]);
    if (Math.max(...v.map(p => p[1])) < 8) continue; // door recesses and plinth trim are not shell seams
    // the hand-modelled pavilion faces (pavilion.ts) leave their own open edges below 24 m: no cap over those
    if (Math.max(...v.map(p => p[1])) < 24 && v.every(p => (p[0] > 70 && p[0] < 90 && p[2] > -52 && p[2] < -38) || (p[0] > 94 && p[0] < 101 && p[2] > -37 && p[2] < -26))) continue;
    // the cap's triangles run against the loop's edges so each boundary edge is paired
    for (let i = 1; i < v.length - 1; i++) out.push(...v[0], ...v[i + 1], ...v[i]);
  }
  return out;
}

/** Lantern stage, copper onion helmet, spire, ball and vane on a pavilion apex. */
function helmet(b: BuildingTools, h: {x: number; z: number; y0: number; top: number}) {
  const {x, z, y0, top} = h, onionR = 0.85, neck = 0.9;
  b.add(new T.CylinderGeometry(0.62, 0.8, neck, 8), 'stone', x, y0 + neck / 2 - 0.05, z);
  const onion = new T.SphereGeometry(1, 10, 8); onion.scale(onionR, 1.25, onionR);
  b.add(onion, 'copper', x, y0 + neck + 0.5, z);
  const spireBase = y0 + neck + 0.5 + 1.0;
  b.add(new T.ConeGeometry(0.3, top - 0.45 - spireBase, 6), 'copper', x, (spireBase + top - 0.45) / 2, z);
  b.add(new T.SphereGeometry(0.16, 6, 4), 'gold', x, top - 0.4, z);
  b.add(new T.BoxGeometry(0.03, 0.4, 0.03), 'gold', x, top - 0.2, z);
  b.add(new T.BoxGeometry(0.4, 0.18, 0.02), 'gold', x + 0.2, top - 0.15, z);
}
